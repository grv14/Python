age = 17 # integer
print(age)
print(type(age))

name = "Gaurav" # string
print(name)
print(type(name))

pi = 3.14 # float
print(pi)
print(type(pi))

is_Completed = True # boolean
print(is_Completed)
print(type(is_Completed))

# Rule of defining a variable in python
# Variable name must start with a letter or an underscore
# They can only contain letters, numbers, and underscores
# Variable names are case-sensitive (age, Age, and AGE are three different variables)
# Avoid using Python keywords as variable names (like 'class', 'for', 'if', etc.)


